//! The suite registry embedded at compile time from `suites/`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::Error;
use crate::hash::suite_hash;
use crate::suite::{SuiteManifest, Tier};

include!(concat!(env!("OUT_DIR"), "/builtin_suites.rs"));

/// A manifest plus its content hash.
#[derive(Debug, Clone)]
pub struct RegisteredSuite {
    /// Parsed manifest.
    pub manifest: SuiteManifest,
    /// `sha256:<hex>` of the canonicalized manifest.
    pub hash: String,
    /// File name in `suites/`, e.g. `rust-quick@1.toml`.
    pub file_name: String,
}

/// Every known suite version, keyed by `id@version`.
#[derive(Debug, Clone, Default)]
pub struct Registry {
    suites: BTreeMap<(String, u32), RegisteredSuite>,
}

impl Registry {
    /// All manifests compiled into this binary.
    pub fn builtin() -> Self {
        let mut reg = Registry::default();
        for (name, text) in BUILTIN {
            reg.insert(name, text)
                .unwrap_or_else(|e| panic!("builtin suite {name} is invalid: {e}"));
        }
        reg
    }

    /// Add a manifest from TOML text. The file name must be `<id>@<version>.toml`.
    pub fn insert(&mut self, file_name: &str, text: &str) -> Result<&RegisteredSuite, Error> {
        let manifest = SuiteManifest::from_toml(text)?;
        let expected = format!("{}.toml", manifest.key());
        if file_name != expected {
            return Err(Error::Invalid(format!(
                "suite file `{file_name}` must be named `{expected}`"
            )));
        }
        let hash = suite_hash(text)?;
        let key = (manifest.id.clone(), manifest.version);
        let entry = RegisteredSuite {
            manifest,
            hash,
            file_name: file_name.to_owned(),
        };
        Ok(self.suites.entry(key).or_insert(entry))
    }

    /// Exact `id@version` lookup.
    pub fn get(&self, id: &str, version: u32) -> Option<&RegisteredSuite> {
        self.suites.get(&(id.to_owned(), version))
    }

    /// Highest version of `id`.
    pub fn latest(&self, id: &str) -> Option<&RegisteredSuite> {
        self.suites
            .range((id.to_owned(), 0)..=(id.to_owned(), u32::MAX))
            .next_back()
            .map(|(_, s)| s)
    }

    /// Highest version of the suite in `tier`.
    pub fn by_tier(&self, tier: Tier) -> Option<&RegisteredSuite> {
        self.latest_all()
            .into_iter()
            .find(|s| s.manifest.tier == tier)
    }

    /// Every version of every suite.
    pub fn all(&self) -> impl Iterator<Item = &RegisteredSuite> {
        self.suites.values()
    }

    /// Highest version of each suite, ordered light to heavy.
    pub fn latest_all(&self) -> Vec<&RegisteredSuite> {
        let mut latest: BTreeMap<&str, &RegisteredSuite> = BTreeMap::new();
        for s in self.suites.values() {
            latest.insert(&s.manifest.id, s);
        }
        let mut v: Vec<_> = latest.into_values().collect();
        v.sort_by_key(|s| (s.manifest.tier, s.manifest.id.clone()));
        v
    }

    /// Lines of `suites.lock`: `id@version sha256:...`, sorted.
    pub fn lockfile(&self) -> String {
        let mut out = String::from(
            "# Generated by `cargo xtask suites-lock`. Released suite versions never change.\n",
        );
        for s in self.suites.values() {
            let _ = writeln!(out, "{} {}", s.manifest.key(), s.hash);
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn suites_lock_matches_builtin_manifests() {
        let committed = include_str!("../../../suites/suites.lock");
        let expected = Registry::builtin().lockfile();
        let entries = |s: &str| -> BTreeMap<String, String> {
            s.lines()
                .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
                .filter_map(|l| l.split_once(' '))
                .map(|(k, v)| (k.to_owned(), v.to_owned()))
                .collect()
        };
        let (committed, expected) = (entries(committed), entries(&expected));
        for (key, hash) in &committed {
            match expected.get(key) {
                Some(h) => assert_eq!(h, hash, "{key} changed without a version bump"),
                None => panic!("{key} is in suites.lock but its manifest was removed"),
            }
        }
        for key in expected.keys() {
            assert!(
                committed.contains_key(key),
                "{key} is missing from suites.lock: run `cargo xtask suites-lock`"
            );
        }
    }
}
